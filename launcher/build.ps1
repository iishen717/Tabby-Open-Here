$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$candidates = @(
    (Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'),
    (Join-Path $env:WINDIR 'Microsoft.NET\Framework\v4.0.30319\csc.exe')
) | Where-Object { Test-Path $_ }
if (-not $candidates) {
    throw 'csc.exe not found. .NET Framework 4 is required.'
}
$csc = $candidates[0]

$out = Join-Path $PSScriptRoot 'tabby.exe'
& $csc -nologo -codepage:65001 -target:winexe -optimize+ -out:$out (Join-Path $PSScriptRoot 'Launcher.cs')
if ($LASTEXITCODE -ne 0) {
    throw "csc failed with exit code $LASTEXITCODE"
}

$base64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($out))
$version = '1.0.0'
$ts = @"
/**
 * Launcher binary (base64).
 * Generated by launcher/build.ps1 - do not edit manually.
 * Source: launcher/Launcher.cs
 */
export const LAUNCHER_VERSION = '$version'
export const LAUNCHER_EXE_BASE64 = '$base64'
"@
$target = Join-Path $root 'src\oh-launcher-exe.ts'
[IO.File]::WriteAllText($target, $ts, [Text.UTF8Encoding]::new($false))
Write-Host "Launcher: $out"
Write-Host "TypeScript: $target"
